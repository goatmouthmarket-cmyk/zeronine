import { parentPort, workerData } from 'node:worker_threads';
import { DatabaseSync } from 'node:sqlite';
import { mkdirSync } from 'node:fs';
import { dirname } from 'node:path';
import { Pool } from 'pg';

let db;
let pool;
let postgres = false;
let lastPrune = 0;

const sqliteSchema = `PRAGMA journal_mode=WAL; PRAGMA synchronous=NORMAL; PRAGMA busy_timeout=1000;
  CREATE TABLE IF NOT EXISTS telemetry_events (
    id INTEGER PRIMARY KEY, schema_version INTEGER NOT NULL, observed_at INTEGER NOT NULL,
    event_type TEXT NOT NULL, market TEXT, source TEXT NOT NULL, data_json TEXT NOT NULL
  );
  CREATE INDEX IF NOT EXISTS telemetry_events_time ON telemetry_events(observed_at, id);
  CREATE INDEX IF NOT EXISTS telemetry_events_market_time ON telemetry_events(market, observed_at, id);
  CREATE INDEX IF NOT EXISTS telemetry_events_type_id ON telemetry_events(event_type, id);`;

async function start() {
  if (workerData.connectionString) {
    postgres = true;
    pool = new Pool({
      connectionString: workerData.connectionString,
      ssl: { rejectUnauthorized: false },
      max: 2,
      connectionTimeoutMillis: 5000,
      idleTimeoutMillis: 30000,
    });
    pool.on('error', () => parentPort.postMessage({ type: 'database-warning' }));
    await pool.query(`CREATE SCHEMA IF NOT EXISTS research_telemetry;
      REVOKE ALL ON SCHEMA research_telemetry FROM PUBLIC, anon, authenticated;
      CREATE TABLE IF NOT EXISTS research_telemetry.events (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        schema_version INTEGER NOT NULL,
        observed_at BIGINT NOT NULL,
        event_type TEXT NOT NULL,
        market TEXT,
        source TEXT NOT NULL,
        data_json TEXT NOT NULL
      );
      CREATE INDEX IF NOT EXISTS telemetry_events_time ON research_telemetry.events(observed_at, id);
      CREATE INDEX IF NOT EXISTS telemetry_events_market_time ON research_telemetry.events(market, observed_at, id);
      CREATE INDEX IF NOT EXISTS telemetry_events_type_id ON research_telemetry.events(event_type, id);
      REVOKE ALL ON ALL TABLES IN SCHEMA research_telemetry FROM PUBLIC, anon, authenticated;
      REVOKE ALL ON ALL SEQUENCES IN SCHEMA research_telemetry FROM PUBLIC, anon, authenticated;`);
  } else {
    mkdirSync(dirname(workerData.path), { recursive: true });
    db = new DatabaseSync(workerData.path);
    db.exec(sqliteSchema);
  }
  parentPort.postMessage({ type: 'ready' });
}

async function writeBatch(events) {
  if (postgres) {
    const payload = JSON.stringify(events.map(event => ({
      schema_version: 1,
      observed_at: event.observedAt,
      event_type: event.type,
      market: event.market,
      source: event.source,
      data_json: JSON.stringify(event.data),
    })));
    await pool.query(`INSERT INTO research_telemetry.events
      (schema_version, observed_at, event_type, market, source, data_json)
      SELECT schema_version, observed_at, event_type, market, source, data_json
      FROM jsonb_to_recordset($1::jsonb) AS batch(
        schema_version INTEGER, observed_at BIGINT, event_type TEXT,
        market TEXT, source TEXT, data_json TEXT
      )`, [payload]);
    return;
  }
  db.exec('BEGIN');
  try {
    const insert = db.prepare('INSERT INTO telemetry_events (schema_version, observed_at, event_type, market, source, data_json) VALUES (?, ?, ?, ?, ?, ?)');
    for (const event of events) insert.run(1, event.observedAt, event.type, event.market, event.source, JSON.stringify(event.data));
    db.exec('COMMIT');
  } catch (error) {
    try { db.exec('ROLLBACK'); } catch {}
    throw error;
  }
}

async function prune() {
  if (workerData.retentionDays <= 0 || Date.now() - lastPrune <= 60_000) return;
  const cutoff = Date.now() - workerData.retentionDays * 86400000;
  if (postgres) {
    await pool.query(`WITH old_rows AS (
      SELECT id FROM research_telemetry.events WHERE observed_at < $1 ORDER BY id LIMIT 5000
    ) DELETE FROM research_telemetry.events AS event USING old_rows WHERE event.id=old_rows.id`, [cutoff]);
  } else {
    db.prepare(`DELETE FROM telemetry_events WHERE id IN (
      SELECT id FROM telemetry_events WHERE observed_at < ? ORDER BY id LIMIT 5000
    )`).run(cutoff);
  }
  lastPrune = Date.now();
}

parentPort.on('message', async (message) => {
  if (message.type === 'batch') {
    try {
      await writeBatch(message.events);
      await prune();
      parentPort.postMessage({ type: 'written', count: message.events.length });
    } catch {
      parentPort.postMessage({ type: 'failed', count: message.events.length });
    }
  } else if (message.type === 'query') {
    try {
      const rows = postgres
        ? (await pool.query(
          'SELECT id, schema_version, observed_at, event_type, market, source, data_json FROM research_telemetry.events WHERE id > $1 ORDER BY id LIMIT $2',
          [message.after, message.limit],
        )).rows
        : db.prepare('SELECT id, schema_version, observed_at, event_type, market, source, data_json FROM telemetry_events WHERE id > ? ORDER BY id LIMIT ?').all(message.after, message.limit);
      parentPort.postMessage({
        type: 'query-result',
        requestId: message.requestId,
        rows: rows.map(row => ({ ...row, id: Number(row.id), observed_at: Number(row.observed_at) })),
      });
    } catch {
      parentPort.postMessage({ type: 'query-result', requestId: message.requestId, error: 'Telemetry database unavailable' });
    }
  } else if (message.type === 'close') {
    try { db?.close(); } catch {}
    try { await pool?.end(); } catch {}
    parentPort.postMessage({ type: 'closed' });
    parentPort.close();
  }
});

start().catch(() => {
  try { db?.close(); } catch {}
  void pool?.end().catch(() => {});
  parentPort.postMessage({ type: 'startup-failed' });
  parentPort.close();
});
